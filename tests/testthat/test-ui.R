test_that("all workflow controls and packaged assets render", {
  withr::local_options(sass.cache = FALSE)
  rendered <- htmltools::renderTags(app_ui(NULL))
  html <- paste(rendered$html, rendered$head)
  expect_match(html, 'id="event-site"', fixed = TRUE)
  expect_match(html, 'id="measured-shell_height_mm"', fixed = TRUE)
  expect_match(html, 'id="visual-add_observation"', fixed = TRUE)
  expect_match(html, 'id="visual-module_type"', fixed = TRUE)
  expect_match(html, '<option value="bags">bags</option>', fixed = TRUE)
  expect_match(html, '<option value="gabion">gabion</option>', fixed = TRUE)
  expect_equal(length(gregexpr('class="notes-info"', html, fixed = TRUE)[[1]]), 4L)
  expect_match(html, "Separate individual notes with a semicolon (;).", fixed = TRUE)
  expect_match(html, 'id="structural-structure_type"', fixed = TRUE)
  expect_match(html, 'id="review-submit"', fixed = TRUE)
  expect_match(html, 'www/form-state.js', fixed = TRUE)
  expect_false(any(vapply(c("download_draft", "recover_draft", "upload_draft", "draft_status", "www/drafts.js"),
    function(text) grepl(text, html, fixed = TRUE), logical(1))))
  expect_match(html, 'www/app.css', fixed = TRUE)
  expect_match(html, 'www/workbook-downloads.js', fixed = TRUE)
  expect_true(file.exists(system.file("app/www/restore-our-shores-logo.jpg", package = "rosoyster")))
})
